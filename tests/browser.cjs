const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const baseURL=process.env.ATLAS_BASE_URL || 'http://127.0.0.1:8002/';
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error' && /Shader Error/.test(m.text()))errors.push(m.text());});
  await page.goto(baseURL);
  await page.waitForFunction(()=>document.querySelector('#mission-count').textContent.includes('109 entries'));
  await page.waitForFunction(()=>document.querySelector('#sky-quality').textContent.includes('5,044'));
  assert(await page.locator('.cluster-marker:visible').count()>0);
  await page.locator('.cluster-marker:visible').first().click();
  assert(await page.locator('#mission-media').evaluate(e=>e.open));
  await page.keyboard.press('Escape');
  await page.locator('#mission-search').fill('Firefly Blue Ghost');
  assert.equal(await page.locator('#mission-select option').count(),5);
  await page.locator('#mission-search').fill('');
  await page.locator('#blue-ghost-focus').click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('LOLA terrain'));
  await page.locator('#grid').check();
  await page.locator('#resource').selectOption('titanium');
  await page.waitForFunction(()=>document.querySelector('#resource-info').textContent.includes('Clementine TiO'));
  await page.locator('#resource').selectOption('');
  await page.locator('#measure').check();
  const bounds=await page.locator('#scene').boundingBox();
  await page.mouse.click(bounds.x+bounds.width*.45,bounds.y+bounds.height*.45);
  await page.mouse.click(bounds.x+bounds.width*.55,bounds.y+bounds.height*.55);
  assert.match(await page.locator('#measurement').textContent(),/km along reference sphere/);
  await page.locator('#measure').uncheck();
  await page.locator('#measure-clear').click();
  await page.locator('[data-mode="surface"]').click();
  await page.waitForTimeout(3000);
  assert(await page.locator('#surface-controls').isVisible());
  const before=Number(await page.locator('#lon').inputValue());
  await page.locator('[data-move="0"]').click();
  assert.notEqual(Number(await page.locator('#lon').inputValue()),before);
  await page.locator('#eye-height').fill('10');
  await page.locator('#eye-height').dispatchEvent('change');
  await page.locator('#view-name').fill('Test lunar traverse');
  await page.locator('#save-view').click();
  assert.match(await page.locator('#view-message').textContent(),/Saved/);
  await page.locator('#shadows').check();
  await page.locator('#map').click();
  await page.locator('#saved-views').selectOption('0');
  assert.equal(await page.locator('#eye-height').inputValue(),'10');
  assert.equal(await page.locator('#shadows').isChecked(),false);
  await page.locator('#resource').selectOption('hydrogen');
  await page.waitForFunction(()=>document.querySelector('#resource-info').textContent.includes('Lunar Prospector'));
  await page.waitForTimeout(2500);
  await page.locator('#save-view').click();
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#mission-count').textContent.includes('109 entries'));
  await page.locator('#saved-views').selectOption('0');
  assert.equal(await page.locator('#resource').inputValue(),'hydrogen');
  const stored=JSON.parse(await page.evaluate(()=>localStorage.getItem('lunar-atlas-viewpoints-v1')))[0].view;
  await page.goto(baseURL+'#view='+encodeURIComponent(JSON.stringify(stored)));
  await page.waitForFunction(()=>document.querySelector('#view-message').textContent.includes('Shared viewpoint restored'));
  assert.equal(await page.locator('#resource').inputValue(),'hydrogen');
  assert.equal(await page.locator('#lat').inputValue(),String(stored.latitude));
  assert.deepEqual(errors,[]);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  console.log('Browser checks passed: WebGL, stars, clusters, search, resource maps, measurements, walking, eye height, shadows, saved/shared views, mobile layout.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
